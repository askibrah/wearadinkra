<?php
declare(strict_types=1);
require_once __DIR__ . '/config.php';
require_once __DIR__ . '/db.php';

$pdo->exec('CREATE TABLE IF NOT EXISTS seo_settings (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    settings TEXT NOT NULL,
    updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=' . DB_CHARSET);

$defaults = [
    'writeTags' => true, 'allowIndex' => true, 'allowFollow' => true,
    'siteTitle' => 'Wear Adinkra | Preserving Ghanaian Heritage',
    'titleTemplate' => '%s | Wear Adinkra',
    'metaDescription' => 'Authentic Ghanaian fashion inspired by Adinkra symbols. Wear your heritage withwearadinkra.',
    'keywords' => 'adinkra, ghanaian fashion, african fashion, wear adinkra, kente, heritage clothing',
    'baseUrl' => APP_URL,
    'ogTitle' => '', 'ogDescription' => '', 'ogImage' => '', 'ogType' => 'website',
    'twitterHandle' => '@wearadinkra', 'twitterTitle' => '', 'twitterDescription' => '', 'twitterImage' => '',
    'themeColor' => '#1C5D99', 'favicon' => '',
    'listListings' => true,
    'gscToken' => '', 'bingToken' => '', 'gaId' => '', 'gtmId' => '', 'adsenseId' => '',
    'orgName' => 'Wear Adinkra', 'orgDescription' => '', 'orgLogo' => '',
    'facebookPage' => '', 'twitterProfile' => '', 'instagramUrl' => '', 'linkedinUrl' => '', 'youtubeUrl' => ''
];

function wa_seo_load(PDO $pdo, array $defaults): array
{
    $row = $pdo->query('SELECT settings FROM seo_settings ORDER BY id DESC LIMIT 1')->fetchColumn();
    if (!$row) return $defaults;
    $saved = json_decode((string)$row, true);
    return is_array($saved) ? array_merge($defaults, $saved) : $defaults;
}

function wa_seo_base(array $s): string
{
    $base = trim((string)($s['baseUrl'] ?? ''));
    return rtrim($base !== '' ? $base : APP_URL, '/');
}

function wa_generate_seo_files(array $s, PDO $pdo): void
{
    $root = dirname(__DIR__) . DIRECTORY_SEPARATOR;
    $base = wa_seo_base($s);
    $index = !empty($s['allowIndex']);
    $follow = !empty($s['allowFollow']);

    $robots = "# Generated by Wear Adinkra SEO settings\n";
    $robots .= "User-agent: *\n";
    $robots .= ($index ? 'Allow: /' : 'Disallow: /') . "\n";
    if (!$follow) $robots .= "Disallow: /*?\n";
    $robots .= 'Sitemap: ' . $base . "/sitemap.xml\n";
    @file_put_contents($root . 'robots.txt', $robots);

    $urls = [$base . '/', $base . '/index.html', $base . '/shop', $base . '/our-story', $base . '/contact'];
    if (!empty($s['listListings'])) {
        $rows = $pdo->query('SELECT id FROM products ORDER BY id')->fetchAll(PDO::FETCH_COLUMN);
        foreach ($rows as $id) $urls[] = $base . '/index.html?product=' . (int)$id;
    }
    $xml = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
    $xml .= '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
    foreach (array_unique($urls) as $u) {
        $xml .= "  <url><loc>" . htmlspecialchars($u, ENT_XML1) . "</loc><changefreq>weekly</changefreq><priority>0.7</priority></url>\n";
    }
    $xml .= "</urlset>\n";
    @file_put_contents($root . 'sitemap.xml', $xml);
}

$method = $_SERVER['REQUEST_METHOD'] ?? 'GET';
$input = wa_input();
$action = isset($input['action']) ? (string)$input['action'] : ($_GET['action'] ?? '');

if ($action === 'meta' || ($method === 'GET' && $action !== 'all')) {
    $s = wa_seo_load($pdo, $defaults);
    wa_json(['ok' => true, 'settings' => $s]);
}

if ($action === 'all') {
    if (empty($_SESSION['admin_id'])) wa_json(['ok' => false, 'message' => 'Admin sign-in required.'], 401);
    wa_json(['ok' => true, 'settings' => wa_seo_load($pdo, $defaults)]);
}

if ($action !== 'save') wa_json(['ok' => false, 'message' => 'Unknown action.'], 400);
if (empty($_SESSION['admin_id'])) wa_json(['ok' => false, 'message' => 'Admin sign-in required.'], 401);
if (!wa_valid_csrf($input)) wa_json(['ok' => false, 'message' => 'Invalid security token.'], 403);

$saved = wa_seo_load($pdo, $defaults);
foreach ($defaults as $key => $val) {
    if (!array_key_exists($key, $input)) continue;
    $value = $input[$key];
    if (is_bool($val)) $saved[$key] = filter_var($value, FILTER_VALIDATE_BOOLEAN);
    else $saved[$key] = is_scalar($value) ? trim((string)$value) : $val;
}
$stmt = $pdo->prepare('DELETE FROM seo_settings');
$stmt->execute();
$stmt = $pdo->prepare('INSERT INTO seo_settings (settings, updated_at) VALUES (?, NOW())');
$stmt->execute([json_encode($saved, JSON_UNESCAPED_UNICODE)]);
wa_generate_seo_files($saved, $pdo);
wa_json(['ok' => true, 'message' => 'SEO settings saved. robots.txt and sitemap.xml regenerated.', 'settings' => $saved]);
